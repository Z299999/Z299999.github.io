#!/usr/bin/env python3
"""Write sdaff-2026/index.html from sdaff-2026/data.json.

The owner wants this page as plain as a professor's homepage: no script, no
images, no interaction, just tables a friend can read row by row. Edit the
data, then run:

    python3 tools/build_sdaff.py
"""
import datetime as dt
import html
import json
import os
import urllib.parse

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIR = os.path.join(REPO, "sdaff-2026")
WEEK = ["周一", "周二", "周三", "周四", "周五", "周六", "周日"]
TYPES = {"feature": "长片", "shorts": "短片合集"}
# Addresses from https://sdaff.org/2026/venues/ (checked 2026-11-04).
ADDRESSES = [
    ("UltraStar Cinemas Mission Valley", "7510 Hazard Center Drive, San Diego, CA 92108"),
    ("San Diego Natural History Museum", "1788 El Prado, San Diego, CA 92101"),
    ("UC San Diego Park & Market", "1100 Market St, San Diego, CA"),
    ("University of San Diego, Warren Auditorium", "5998 Alcalá Park, San Diego, CA"),
]
# Google Maps opens the app on phones that have it, the website elsewhere.
DIM = ' class="dim"'
MAPS = "https://www.google.com/maps/search/?api=1&query="
EVENT_TYPES = {
    "reception": "酒会", "social": "Happy Hour", "awards": "颁奖",
    "artist_talk": "讲座", "special_screening": "特别场",
    "industry_only": "业内限定", "students": "学校项目",
}
e = html.escape


def day(date):
    d = dt.date.fromisoformat(date)
    return f"{d.month:02d}/{d.day:02d}（{WEEK[d.weekday()]}）"


def end_of(s):
    m = int(s["start"][:2]) * 60 + int(s["start"][3:]) + s["slotMinutes"]
    return f"{m // 60:02d}:{m % 60:02d}"


def link(url, text):
    return f'<a href="{e(url)}">{e(text)}</a>'


def main():
    d = json.load(open(os.path.join(DIR, "data.json"), encoding="utf-8"))
    # Screenings the owner dropped stay in data.json, marked "dropped", and are
    # left off the page; so is a film with no screening left.
    d["screenings"] = [s for s in d["screenings"] if not s.get("dropped")]
    kept = {s["title"] for s in d["screenings"]}
    d["titles"] = [t for t in d["titles"] if t["id"] in kept]
    titles = {t["id"]: t for t in d["titles"]}

    # "dim": screenings the owner is lukewarm on, shown in pale grey.
    rows, numbers, dim_titles = [], {}, {}
    for n, s in enumerate(sorted(d["screenings"], key=lambda s: (s["date"], s["start"])), 1):
        t = titles[s["title"]]
        num = f'{n}（{day(s["date"])[:5]}）'
        numbers.setdefault(t["id"], []).append(f'<span class="dim">{num}</span>' if s.get("dim") else num)
        dim_titles[t["id"]] = dim_titles.get(t["id"], True) and bool(s.get("dim"))
        notes = []
        if s["qa"]:
            notes.append("映后 Q&amp;A")
        if s["reception"]:
            notes.append("Reception " + e(s["reception"]))
        length = f'{t["minutes"]} 分钟'
        if s["slotMinutes"] != t["minutes"]:
            length += f'（排片时段 {s["slotMinutes"]}）'
        rows.append(
            f'<tr{DIM if s.get("dim") else ""}><td>{n}</td><td>{day(s["date"])}</td><td>{e(s["start"])}–{end_of(s)}</td>'
            f'<td>{e(s["venue"])}</td><td>{link(t["url"], t["name"])}</td><td>{"<br>".join(e(x) for x in t["director"].split("、"))}</td><td>{TYPES[t["type"]]}</td>'
            f'<td>{length}</td><td>{e(s["price"])}</td>'
            f'<td>{e(t["tagline"])}</td><td>{"；".join(notes)}</td></tr>')

    # One row per film or program; its screening numbers tie it to the table above.
    by_film = {}
    for kind in TYPES:
        by_film[kind] = "\n".join(
            f'<tr{DIM if dim_titles[t["id"]] else ""}><td>{link(t["url"], t["name"])}</td>'
            + (f'<td>{"<br>".join(e(x) for x in t["director"].split("、"))}</td>' if kind == "feature" else "")
            + f'<td>{t["minutes"]} 分钟</td><td>{e(t["price"])}</td><td>{e(t["tagline"])}</td>'
            f'<td>{"<br>".join(numbers[t["id"]])}</td></tr>'
            for t in d["titles"] if t["type"] == kind)
    counts = {k: sum(t["type"] == k for t in d["titles"]) for k in TYPES}

    events = []
    for v in sorted(d["events"], key=lambda v: (v["date"], v["start"] or "")):
        time = "时间待定"
        if v["start"]:
            time = v["start"] + (f'–{v["end"]}' if v["end"] else " 起")
        events.append(
            f'<tr><td>{day(v["date"])}</td><td>{e(time)}</td>'
            f'<td>{link(v["officialUrl"], v["title"])}</td>'
            f'<td>{EVENT_TYPES.get(v["type"], "")}</td>'
            f'<td>{e(v["eligibility"])}</td><td>{e(v["venue"])}</td></tr>')

    shorts = []
    for t in d["titles"]:
        if t["type"] == "shorts":
            items = "、".join(t["highlightedShorts"]) or "（整组候选，没有单独标出的短片）"
            shorts.append(f'<li>{link(t["url"], t["name"])}：{e(items)}</li>')

    verified = d.get("verified", {}).get("date")
    page = f"""<!DOCTYPE html>
<html lang="zh-CN">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>SDAFF 2026 候选片单（中文版）</title>
<!-- Unlisted, not private: anyone with the link can read it. Generated by
     tools/build_sdaff.py from data.json; edit those, not this file. -->
<meta name="robots" content="noindex,nofollow">
<style>
body {{ max-width: 1240px; margin: 2em auto; padding: 0 16px; font-family: Georgia, "Songti SC", serif; line-height: 1.5; color: #000; background: #fff; }}
table {{ border-collapse: collapse; width: 100%; font-size: 15px; }}
th, td {{ border: 1px solid #999; padding: 4px 6px; text-align: left; vertical-align: top; }}
th {{ background: #eee; }}
th:first-child, td:first-child, td:nth-child(2), .films td:nth-child(3), .films td:nth-child(9) {{ white-space: nowrap; }}
.scroll {{ overflow-x: auto; }}
.dim, .dim td, .dim a {{ color: #aaa; }}
a {{ color: #00e; }}
</style>
</head>
<body>
<h1>SDAFF 2026 候选片单（中文版）</h1>
<p>2026 圣地亚哥亚洲电影节（San Diego Asian Film Festival），11 月 5 日至 14 日。
以下是个人整理的候选，都还没有买票；不是电影节官方页面，一切以
<a href="{e(d["officialSchedule"])}">官方排片</a>为准。</p>

<h2>电影与短片合集（按场次）</h2>
<div class="scroll"><table class="films">
<tr><th>编号</th><th>日期</th><th>时间</th><th>影院</th><th>片名</th><th>导演</th><th>类型</th><th>片长</th><th>票价</th><th>简介</th><th>备注</th></tr>
{chr(10).join(rows)}
</table></div>

<h2>按影片</h2>
<p>每部片一行；「场次」是上表的编号，括号里是日期。</p>

<h3>长片（{counts["feature"]} 部）</h3>
<div class="scroll"><table>
<tr><th>片名</th><th>导演</th><th>片长</th><th>票价</th><th>简介</th><th>场次</th></tr>
{by_film["feature"]}
</table></div>

<h3>短片合集（{counts["shorts"]} 个）</h3>
<div class="scroll"><table>
<tr><th>合集</th><th>片长</th><th>票价</th><th>简介</th><th>场次</th></tr>
{by_film["shorts"]}
</table></div>

<h2>短片合集里的重点短片</h2>
<ul>
{chr(10).join(shorts)}
</ul>

<h2>电影节特别活动</h2>
<div class="scroll"><table>
<tr><th>日期</th><th>时间</th><th>活动</th><th>类型</th><th>参加条件</th><th>地点</th></tr>
{chr(10).join(events)}
</table></div>

<h2>影院地址</h2>
<ul>
{chr(10).join(f'<li>{e(n)}：{link(MAPS + urllib.parse.quote(n + ", " + a), a)}</li>' for n, a in ADDRESSES)}
</ul>

<h2>说明</h2>
<ul>
<li>同一部片出现两次，是两个不同场次。结束时间按片长估算。</li>
<li>上面 {len(rows)} 个场次都在 UltraStar Cinemas Mission Valley（{day(verified) if verified else ""}对照官网每部片的页面核对过）；电影节其他场馆的放映不在这份候选里。</li>
<li>Q&amp;A 和 Reception 的结束时间官方大多没有公布。</li>
<li>Filmmaker Brunch 只限业内嘉宾；Youth Days 是合作学校的学生项目，普通观众不能参加。</li>
<li>来源：<a href="{e(d["officialSchedule"])}">SDAFF 2026 Schedule</a>、<a href="{e(d["officialSpecialEvents"])}">Special Events</a>{f"，{day(verified)}核对过" if verified else ""}。</li>
</ul>
</body>
</html>
"""
    with open(os.path.join(DIR, "index.html"), "w", encoding="utf-8") as f:
        f.write(page)
    print("wrote sdaff-2026/index.html:", len(rows), "screenings,", len(events), "events,", len(shorts), "programs")


if __name__ == "__main__":
    main()
